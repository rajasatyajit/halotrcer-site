// Re-cuts the Permanent Marker subset to what the site uses: builds both modes, collects every
// character set in Marker on all three hosts (scripts/lib/marker.ts), writes
// src/lib/marker-glyphs.ts, then re-runs scripts/subset-fonts.ts. Run it when check:marker
// names a missing glyph. Needs fonttools (pyftsubset) and woff2_compress. Leaves dist/ holding
// the launched (fixture) build.
import { spawnSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { distMarkerChars } from './lib/marker.ts';

const run = (cmd: string, args: string[], env: Record<string, string> = {}) => {
  const r = spawnSync(cmd, args, { stdio: 'inherit', env: { ...process.env, ...env } });
  if (r.status !== 0) process.exit(r.status ?? 1);
};
const collect = (into: Set<string>) => {
  for (const { chars } of distMarkerChars()) for (const c of chars) if (c.trim()) into.add(c);
};

const used = new Set<string>();
run('node', ['scripts/build.ts'], { LAUNCHED: 'false' });
collect(used);
run('node', ['scripts/fixture-releases.ts']);
run('node', ['scripts/build.ts'], {
  LAUNCHED: 'true',
  RELEASE_DATA_DIR: '.cache/fixture-releases',
  ALLOW_CANDIDATE_SCRIPTS: '1',
});
collect(used);

const glyphs = [...used].sort((a, b) => (a.codePointAt(0) ?? 0) - (b.codePointAt(0) ?? 0)).join('');
writeFileSync(
  'src/lib/marker-glyphs.ts',
  `// Generated by \`npm run font:marker\`: every character the built pages of all three hosts set
// in Permanent Marker, in both modes. Do not edit by hand; re-run the script instead.
export const MARKER_USED =
  ${JSON.stringify(glyphs)};
`,
);
console.log(`${used.size} characters set in Marker: ${glyphs}`);
// A new process, so it imports the regenerated glyph list.
run('node', ['scripts/subset-fonts.ts']);
